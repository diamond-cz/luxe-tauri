use std::env;
use std::fs;
use std::path::{Path, PathBuf};

const MAX_MTK_HEADERS: usize = 512;
const MAX_MTK_HEADER_BYTES: u64 = 512 * 1024;
const MAX_MTK_HEADERS_BYTES: u64 = 32 * 1024 * 1024;
const MTK_MODULES: &[&str] = &[
    "AE", "AF", "AWB", "ISP", "STROBE", "SHADING", "CMN", "MF", "N3D", "SENSOR", "RESVA", "RESVB",
    "STRING",
];

fn collect_headers(root: &Path, directory: &Path, files: &mut Vec<PathBuf>) {
    println!("cargo:rerun-if-changed={}", directory.display());
    let mut entries: Vec<_> = fs::read_dir(directory)
        .expect("read bundled MTK header directory")
        .map(|entry| entry.expect("read MTK header entry").path())
        .collect();
    entries.sort();
    for path in entries {
        let metadata = fs::symlink_metadata(&path).expect("read MTK header metadata");
        assert!(
            !metadata.file_type().is_symlink(),
            "MTK header symlinks are not allowed"
        );
        if metadata.is_dir() {
            assert!(path.strip_prefix(root).unwrap().components().count() <= 3);
            collect_headers(root, &path, files);
        } else {
            assert!(metadata.is_file(), "MTK resources must be regular files");
            assert!(
                metadata.len() <= MAX_MTK_HEADER_BYTES,
                "MTK header exceeds per-file budget"
            );
            files.push(path);
            assert!(
                files.len() <= MAX_MTK_HEADERS,
                "MTK header count exceeds budget"
            );
        }
    }
}

fn embed_mtk_headers() {
    let manifest = PathBuf::from(env::var_os("CARGO_MANIFEST_DIR").unwrap());
    let root = manifest.join("resources/mtk_exif/headers");
    let mut files = Vec::new();
    collect_headers(&root, &root, &mut files);
    files.sort();
    let mut total_bytes = 0u64;
    let mut source = String::from("// Generated by build.rs; headers are data, never executed.\nstatic HEADER_SOURCES: &[HeaderSource] = &[\n");
    for path in files {
        total_bytes += fs::metadata(&path).unwrap().len();
        assert!(
            total_bytes <= MAX_MTK_HEADERS_BYTES,
            "MTK headers exceed total byte budget"
        );
        let relative = path
            .strip_prefix(&root)
            .unwrap()
            .to_str()
            .unwrap()
            .replace('\\', "/");
        let parts: Vec<_> = relative.split('/').collect();
        assert!(
            matches!(parts.len(), 2 | 4),
            "invalid MTK header path: {relative}"
        );
        let module = parts[0];
        assert!(
            MTK_MODULES.contains(&module),
            "unknown MTK module: {module}"
        );
        let signature = if parts.len() == 4 {
            assert_eq!(parts[1], "variants");
            assert!(parts[2].len() == 8 && parts[2].bytes().all(|byte| byte.is_ascii_hexdigit()));
            format!("Some(0x{})", parts[2])
        } else {
            "None".to_string()
        };
        let filename = parts.last().unwrap();
        let stem = filename
            .strip_suffix(".h")
            .or_else(|| filename.strip_suffix(".ha"))
            .expect("only .h/.ha MTK enum resources are allowed");
        let words: Vec<_> = stem.split('_').collect();
        assert!(
            words.len() == 4 && words[0] == module,
            "invalid MTK header name: {relative}"
        );
        let generation: u8 = words[1].parse().expect("MTK header generation");
        assert!(
            matches!(generation, 5 | 6),
            "unsupported MTK header generation"
        );
        let low: u16 = words[2].parse().expect("MTK header low version");
        let high: u16 = words[3].parse().expect("MTK header high version");
        assert_eq!(
            stem,
            format!("{module}_{generation}_{low}_{high}"),
            "noncanonical MTK version filename"
        );
        let version = (u32::from(high) << 16) | u32::from(low);
        // include_str! also rejects non-UTF8 headers at compile time. Absolute
        // build paths only occur in generated Rust, never in the diagnostic API.
        let absolute = path.to_str().unwrap().replace('\\', "/");
        source.push_str(&format!(
            "    HeaderSource {{ module: {module:?}, generation: {generation}, version: {version}, signature: {signature}, path: {relative:?}, text: include_str!({absolute:?}) }},\n"
        ));
        println!("cargo:rerun-if-changed={}", path.display());
    }
    source.push_str("];\n");
    fs::write(
        PathBuf::from(env::var_os("OUT_DIR").unwrap()).join("mtk_headers.rs"),
        source,
    )
    .expect("write embedded MTK header catalog");
}

fn main() {
    embed_mtk_headers();
    tauri_build::build()
}
